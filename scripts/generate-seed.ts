/**
 * Generates supabase/seed.sql from the TypeScript fixtures so demo mode and seeded databases match.
 * Run: npm run seed:generate
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  fixtureAwards,
  fixtureExercises,
  fixtureGameMedia,
  fixtureGames,
  fixturePlayers,
  fixturePosts,
  fixtureSeasons,
  fixtureStatLines,
  fixtureTeam,
} from "../src/fixtures";
import type { Media } from "../src/types/domain";

type Value = string | number | boolean | null | undefined | string[];

function lit(v: Value): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[], { identity = false } = {}): string {
  if (rows.length === 0) return "";
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")})${identity ? " overriding system value" : ""} values\n${values};\n`;
}

function mediaRow(m: Media, owner: { gameId?: number | null; postId?: number | null } = {}): Record<string, Value> {
  return {
    id: m.id,
    kind: m.kind,
    storage_key: m.storageKey,
    poster_key: m.posterKey,
    title: m.title,
    caption: m.caption,
    mime_type: m.mimeType,
    size_bytes: m.sizeBytes,
    width: m.width,
    height: m.height,
    duration_seconds: m.durationSeconds,
    game_id: owner.gameId ?? null,
    post_id: owner.postId ?? null,
    sort_order: m.sortOrder,
  };
}

